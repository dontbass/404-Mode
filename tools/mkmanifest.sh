#!/bin/sh
# Regenerate MANIFEST: the files install.sh fetches one by one when the
# GitHub tarball is unreachable (raw / jsDelivr fallback). Symlinks are
# skipped — the installer recreates them.
cd "$(dirname "$0")/.." || exit 1
{
	echo "# generated by tools/mkmanifest.sh — do not edit"
	git ls-files -s luci-theme-404mode luci-theme-404mode-modemwebui | awk '$1 != "120000" { print $4 }'
} > MANIFEST
